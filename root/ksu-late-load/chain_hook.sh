#!/system/bin/sh
# FNE-AN00 KernelSU late-load chain (ghostlock root-child hook).
# Launched detached (setsid) by the patched .ghostlock_root.sh right after
# the early SELinux policy fix: this shell runs uid 0, u:r:kernel:s0,
# SELinux permissive, and sig_enforce has been cleared by W1b (--write1,
# mode-5 write). All output to chain.log. The final re-enable of enforcing
# may kill this shell (FNE kills kernel:s0 processes at the flip) — by
# design it is the very last statement.
D=/data/local/tmp/ksu_fne
L=$D/chain.log
ST=$D/chain_status
# DRY_RUN=1: 验证模式（已 root+KSU 的设备上检验新 chain 逻辑用）。
# 只读验证 sig/slide/merge 并输出统计，跳过 bind-mount、magiskpolicy、
# insmod；输出直打控制台不写 chain.log。真实链勿设。
DRY=${DRY_RUN:-0}
export PATH=/system/bin:/system/xbin:/vendor/bin:$PATH
if [ "$DRY" != "1" ]; then exec >>$L 2>&1; fi
echo running > $ST
echo "=== chain start $(date) pid=$$ dry=$DRY ==="
id 2>&1; getenforce 2>&1
sync

# idempotence: a second hook launch on the same boot must not double-load
if grep -q kernelsu /proc/modules 2>/dev/null; then
  if [ "$DRY" = "1" ]; then
    echo "[dry-run] kernelsu already loaded - continuing for validation"
  else
    echo "kernelsu already loaded - nothing to do"
    echo ok > $ST
    exit 0
  fi
fi

# --- gate 1: W1b result (sig_enforce must be N) ---
sv=$(cat /sys/module/module/parameters/sig_enforce 2>/dev/null)
echo "sig_enforce=$sv"
if [ "$sv" != "N" ] && [ "$sv" != "0" ]; then
  echo "!! sig_enforce still set (W1b missed this boot) - aborting; device"
  echo "   stays permissive; reboot + regrind retries W1b"
  echo sigfail > $ST
  sync
  exit 1
fi

# --- oops protection during insmod ---
po=$(cat /proc/sys/kernel/panic_on_oops 2>/dev/null); po=${po:-1}
echo "panic_on_oops=$po"
if [ "$DRY" != "1" ]; then echo 0 > /proc/sys/kernel/panic_on_oops; fi

# --- pristine policy snapshot (before magiskpolicy; feeds the module's
#     pristine_policy param for the selinux_hide backup) ---
if [ "$DRY" != "1" ]; then
  cat /sys/fs/selinux/policy > $D/pristine_policy 2>/dev/null \
    && echo "pristine policy: $(wc -c < $D/pristine_policy) bytes"
fi

# --- fake kallsyms: runtime-KASLR-adjusted symbol table (generated by the
#     root child from fne_syms.txt + the boot's slide.txt; FNE re-slides
#     every boot, slide-0 addresses would patch wrong .ko entries and
#     panic on insmod). Covers every SHN_UNDEF of the .ko incl. the 32
#     non-kallsyms symbols. Bind-mounted over /proc/kallsyms for
#     load_ko's dynamic resolution. ---
if [ ! -s $D/fake_ksyms.txt ]; then
  echo "!! fake_ksyms.txt missing/empty (exploit did not generate the"
  echo "   runtime kallsyms) - aborting; device stays permissive"
  echo noksyms > $ST
  sync
  exit 1
fi
kr=$(cat /proc/sys/kernel/kptr_restrict 2>/dev/null); echo "kptr_restrict=$kr"
echo 0 > /proc/sys/kernel/kptr_restrict

# --- 留存现场: 此刻 root + kptr_restrict=0, 完整真实 kallsyms 可读。
# 每次运行都 dump: (a) 供主机端离线分析异机内核差异; (b) 即下方 merge 的数据源。
cat /proc/kallsyms > $D/real_kallsyms.txt 2>/dev/null
echo "real kallsyms dumped: $(wc -l < $D/real_kallsyms.txt 2>/dev/null) lines"

# --- slide sanity on a DATA symbol (init_cred): data symbols never have
# CFI/LLVM name variants, so a mismatch here is a REAL slide error.
# KASLR slide is 2MB-aligned: aligned diff = wrong slide (fatal — the ~32
# non-kallsyms syms would insmod wrong addresses); non-aligned diff =
# binary drift vs FNE (fatal too — data layout differs, fne_syms unusable).
R=$(grep -m1 " init_cred$" /proc/kallsyms 2>/dev/null | cut -d' ' -f1)
F=$(grep -m1 " init_cred$" $D/fake_ksyms.txt 2>/dev/null | cut -d' ' -f1)
if [ -n "$R" ] && [ "$R" != "0000000000000000" ] && [ "$R" != "$F" ]; then
  case "$R$F" in
    *[!0-9a-fA-F]*) DIFF=unknown; AL=unknown ;;
    *) DIFF=$(( 0x$R - 0x$F )); AL=$(( DIFF % 0x200000 )) ;;
  esac
  echo "!! init_cred mismatch: real=$R fake=$F diff=$DIFF aligned=$AL"
  cp /sys/fs/selinux/policy $D/pristine_policy 2>/dev/null
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null
  echo slidemismatch > $ST
  sync
  exit 1
fi
echo "slide verified: init_cred=$F (real=$R)"

# --- merge: REAL kallsyms wins per exact symbol name; fake (slide-derived
# from FNE fne_syms) only fills names absent from real kallsyms (the ~32
# non-kallsyms syms). Immune to per-symbol binary drift (LSA commit_creds
# +0x20 case): every kernel-visible name gets its true runtime address.
# Fallback: names carrying $hash suffixes join on the stripped key.
awk -v stats=$D/merge.stats '
  NR==FNR { if ($1 != "0000000000000000") { if (!($3 in r)) r[$3]=$1
             k=$3; sub(/\$.*/, "", k); if (!(k in rs)) rs[k]=$1 }
           next }
  { out=$0
    if ($3 in r) { if (r[$3] != $1) d++; out=r[$3] " " $2 " " $3; o++ }
    else { k=$3; sub(/\$.*/, "", k)
           if (k in rs) { if (rs[k] != $1) d++; out=rs[k] " " $2 " " $3; o++ }
           else n++ }
    print out }
  END { printf "%d overlaid from real kallsyms, %d kept slide-derived, %d drift-fixed\n", o, n, d+0 > stats }' \
  /proc/kallsyms $D/fake_ksyms.txt > $D/fake_kallsyms
if [ ! -s $D/fake_kallsyms ]; then
  echo "!! kallsyms merge produced empty file - aborting"
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null
  echo mergefail > $ST
  sync
  exit 1
fi
echo "merge: $(cat $D/merge.stats 2>/dev/null)"

# --- dry-run 止点: merge 验证完毕, 不动 mount/policy/insmod, 收尾退出 ---
if [ "$DRY" = "1" ]; then
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "[dry-run] VALIDATION OK - sig_enforce/slide/merge 全部通过;"
  echo "[dry-run] 未执行: bind-mount / magiskpolicy / load_ko (insmod)"
  echo dryok > $ST
  sync
  exit 0
fi

if ! mount --bind $D/fake_kallsyms /proc/kallsyms; then
  echo "!! fake kallsyms bind-mount failed - restoring and aborting"
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null
  echo mountfail > $ST
  sync
  exit 1
fi
echo "fake kallsyms bind-mounted ($(wc -l < $D/fake_kallsyms) lines)"

# --- SELinux rules for the ksu domain, live, BEFORE the module (late load
#     never applies rules itself; they must pre-exist for post-enforce) ---
$D/magiskpolicy --apply $D/ksu_rules --live 2>&1
mpc=$?
echo "magiskpolicy exit=$mpc"
if [ $mpc -ne 0 ]; then
  echo "!! magiskpolicy failed - unmounting and aborting (loading the module"
  echo "   without rules would brick KSU at the enforce flip)"
  umount /proc/kallsyms 2>/dev/null
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null
  echo polfail > $ST
  sync
  exit 1
fi
ctx=$(cat /proc/self/attr/current 2>/dev/null)
echo "policy injected (ctx=$ctx)"

# --- load the module ---
$D/kmsg_dumper $D/kmsg_cap.txt 2>$D/kmsg_dumper.err &
KPID=$!
sleep 1
$D/load_ko $D/kernelsu.ko "allow_shell=1 pristine_policy=$D/pristine_policy"
lrc=$?
echo "load_ko exit=$lrc"
sleep 2
sync
kill $KPID 2>/dev/null

if ! grep -q kernelsu /proc/modules 2>/dev/null; then
  echo "!! MODULE NOT LOADED - see kmsg_cap.txt / loadko section above;"
  echo "   restoring sysctls, leaving permissive for post-mortem"
  tail -n 30 $D/kmsg_cap.txt 2>/dev/null
  umount /proc/kallsyms 2>/dev/null
  echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null
  echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null
  echo loadfail > $ST
  sync
  exit 1
fi
echo "=== KernelSU module loaded ==="
grep kernelsu /proc/modules

# --- userspace bring-up: real ksud stages ---
$D/ksud post-fs-data > $D/stage_postfs.log 2>&1; echo "post-fs-data exit=$?"
$D/ksud services > $D/stage_services.log 2>&1; echo "services exit=$?"
$D/ksud boot-completed > $D/stage_boot.log 2>&1; echo "boot-completed exit=$?"
$D/ksud install > $D/stage_install.log 2>&1; echo "install exit=$?"
ls -la /data/adb/ksud 2>&1

# --- restore system state (before the enforce flip) ---
umount /proc/kallsyms 2>/dev/null && echo "kallsyms unmounted"
echo "$kr" > /proc/sys/kernel/kptr_restrict 2>/dev/null && echo "kptr restored=$kr"
echo "$po" > /proc/sys/kernel/panic_on_oops 2>/dev/null && echo "panic_on_oops restored=$po"
rm -f $D/fake_kallsyms $D/fake_ksyms.txt $D/pristine_policy
echo ok > $ST
sync

# --- LAST STEP: re-enable enforcing. On FNE this may kill this shell
#     (kernel:s0); everything above is already done and flushed. ---
echo "=== flipping SELinux enforcing (last step; shell may die here) ==="
echo 1 > /sys/fs/selinux/enforce 2>&1
sleep 1
echo "enforce=$(cat /sys/fs/selinux/enforce 2>/dev/null) - chain complete"
echo "=== chain end $(date) ==="
